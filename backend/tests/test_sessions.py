def test_out_of_order_events_are_refused(client, db):
    body = load("clean")
    body["events"][5]["t"], body["events"][6]["t"] = \
        body["events"][6]["t"], body["events"][5]["t"]
    r = post(client, body)
    assert r.status_code == 422
    assert "increasing" in r.text
    assert count(db, models.Session) == 0


def test_duplicate_event_timestamps_are_refused(client):
    body = load("clean")
    body["events"][6]["t"] = body["events"][5]["t"]
    assert post(client, body).status_code == 422


